  precioPyg: number;
  precioRetailReferencia?: number; // Precio de referencia en Asunción / Retail (ej. Nissei)
  fletePyg: number;
  tipoFlete: "REGULAR" | "PESADO" | string;
  stock: number;
  img: string;
  galeria?: string[];
  colores?: string[];
  descripcion?: string;
  destacados?: string[];
  contenidoCaja?: string[];
  esTopVentas?: boolean;
  esOferta?: boolean;
